def new(n):return Image.new('RGBA',(n*S,n*S),(0,0,0,0))
def tools(im):
    d=ImageDraw.Draw(im,'RGBA');k=im.width/100;w=max(1,int(1.5*k))
    R=lambda b,f,r=4,o=O:d.rounded_rectangle([v*k for v in b],r*k,fill=f,outline=o,width=w)
    E=lambda b,f,o=O:d.ellipse([v*k for v in b],fill=f,outline=o,width=w)
    G=lambda p,f,o=O:(d.polygon([(x*k,y*k) for x,y in p],fill=f),(d.line([(x*k,y*k) for x,y in p+[p[0]]],fill=o,width=w,joint='curve') if o else None))
    L=lambda p,f,wd=1.5:d.line([(x*k,y*k) for x,y in p],fill=f,width=max(1,int(wd*k)))
    return d,k,R,E,G,L
def seg(a,b,w0,w1=None):
    w1=w0 if w1 is None else w1;dx,dy=b[0]-a[0],b[1]-a[1];l=math.hypot(dx,dy);nx,ny=-dy/l,dx/l
    return [(a[0]+nx*w0,a[1]+ny*w0),(b[0]+nx*w1,b[1]+ny*w1),(b[0]-nx*w1,b[1]-ny*w1),(a[0]-nx*w0,a[1]-ny*w0)]
def pt(a,ang,l):return(a[0]+math.cos(math.radians(ang))*l,a[1]+math.sin(math.radians(ang))*l)
